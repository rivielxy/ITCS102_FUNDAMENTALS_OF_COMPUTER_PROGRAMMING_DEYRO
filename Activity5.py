# Arithmetic Operators

a = 8
b = 6
c = 0

print("A = ", a)
print("B = ", b)
c = a + b
print("The sum of A and B is ", c) 
c = a - b
print("The difference of A and B is ", c) 
c = a * b
print("The multiplication of A and B is ", c) 
c = a / b
print("The division of A and B is ", c) 
c = a % b
print("The modulo of A and B is ", c) 
c = a ** b
print("The exponent of A to the power of B is ", c) 
c = a // b
print("The floor division of A and B is ", c) 